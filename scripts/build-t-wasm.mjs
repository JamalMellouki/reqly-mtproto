/** Compiles the T-table WAT into embedded base64 + a real .wasm asset. */
import { readFileSync, writeFileSync } from "node:fs"
import { createRequire } from "node:module"

const require = createRequire(import.meta.url)
const factory = require("wabt")
const wabt = typeof factory === "function" ? await factory() : factory

const wat = readFileSync(new URL("./aes-ige-t.wat", import.meta.url), "utf8")
const parsed = wabt.parseWat("aes-ige-t.wat", wat, {})
const binary = Buffer.from(parsed.toBinary({ log: false, write_debug_names: false }).buffer)
parsed.destroy()

writeFileSync(
  new URL("../src/embedded-wasm.ts", import.meta.url),
  `// GENERATED by scripts/build-t-wasm.mjs — do not edit.\nexport const EMBEDDED_WASM_BASE64 = ${JSON.stringify(binary.toString("base64"))}\n`,
)
writeFileSync(new URL("../src/aes-ige.wasm", import.meta.url), binary)
console.log(JSON.stringify({ ok: true, bytes: binary.length }))
